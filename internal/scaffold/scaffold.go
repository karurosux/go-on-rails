// Package scaffold implements `gor new`: it renders the full project tree
// from templates/project and runs the initial setup commands.
package scaffold

import (
	"fmt"
	"hash/fnv"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/karurosux/go-on-rails/internal/deps"
	"github.com/karurosux/go-on-rails/internal/render"
	"github.com/karurosux/go-on-rails/internal/run"
	"github.com/karurosux/go-on-rails/templates"
)

// Data is passed to every project template.
type Data struct {
	AppName   string
	Module    string
	DBPort    int    // host port for the dev Postgres, unique per app name
	GoVersion string // go directive for go.mod, e.g. "1.27" — enforced by the toolchain
	NodeMajor int    // Node major for engines/.nvmrc/Dockerfile, e.g. 24
}

// goVersion returns the local Go version as "major.minor" for the go.mod
// directive, falling back to a safe floor if detection fails.
func goVersion() string {
	out, err := exec.Command("go", "env", "GOVERSION").Output() // e.g. "go1.27.2"
	v := strings.TrimPrefix(strings.TrimSpace(string(out)), "go")
	if parts := strings.Split(v, "."); err == nil && len(parts) >= 2 {
		return parts[0] + "." + parts[1]
	}
	return "1.25"
}

// nodeMajor returns the local Node major version, falling back to a safe
// floor if detection fails.
func nodeMajor() int {
	out, err := exec.Command("node", "--version").Output() // e.g. "v24.9.0"
	v := strings.TrimPrefix(strings.TrimSpace(string(out)), "v")
	if major, convErr := strconv.Atoi(strings.Split(v, ".")[0]); err == nil && convErr == nil && major > 0 {
		return major
	}
	return 22
}

// dbPort derives a stable host port from the app name so several gor apps
// (and a locally installed Postgres on 5432) can run side by side.
func dbPort(name string) int {
	h := fnv.New32a()
	_, _ = h.Write([]byte(name))
	return 5433 + int(h.Sum32()%500)
}

// Options configures `gor new`.
type Options struct {
	Name        string
	Module      string // defaults to Name
	SkipInstall bool   // skip go mod tidy / npm install / git init
}

// New creates a project at dir (./<name> relative to cwd).
func New(opts Options) error {
	required := []string{"go"}
	if !opts.SkipInstall {
		required = append(required, "node", "npm", "git")
	}
	if err := deps.Check(required...); err != nil {
		return err
	}

	dir := opts.Name
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		return fmt.Errorf("directory %s already exists and is not empty", dir)
	}

	data := Data{
		AppName:   opts.Name,
		Module:    opts.Module,
		DBPort:    dbPort(opts.Name),
		GoVersion: goVersion(),
		NodeMajor: nodeMajor(),
	}
	if data.Module == "" {
		data.Module = opts.Name
	}

	fmt.Printf("Creating %s...\n", dir)
	err := fs.WalkDir(templates.FS, "project", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel := strings.TrimPrefix(path, "project/")
		out := filepath.Join(dir, strings.TrimSuffix(rel, ".tmpl"))
		content, err := render.File(path, data)
		if err != nil {
			return err
		}
		if err := render.Write(out, content, false); err != nil {
			return err
		}
		fmt.Printf("  create  %s\n", strings.TrimSuffix(rel, ".tmpl"))
		return nil
	})
	if err != nil {
		return err
	}

	// Empty dirs that must exist (and survive git): migrations, queries,
	// and web/dist so //go:embed always has something to embed.
	for _, keep := range []string{"migrations", "queries", "web/dist"} {
		if err := render.Write(filepath.Join(dir, keep, ".gitkeep"), nil, false); err != nil {
			return err
		}
	}

	if opts.SkipInstall {
		fmt.Println("\nSkipped go mod tidy, npm install, and git init (--skip-install).")
		return printNextSteps(opts.Name)
	}

	fmt.Println("\nFetching Go dependencies (go mod tidy)...")
	if err := run.Command(dir, "go", "mod", "tidy"); err != nil {
		return fmt.Errorf("go mod tidy failed: %w", err)
	}

	fmt.Println("Installing frontend packages (npm install)...")
	if err := run.CommandQuiet(filepath.Join(dir, "web"), "npm", "install", "--no-fund", "--no-audit"); err != nil {
		return fmt.Errorf("npm install failed: %w", err)
	}

	fmt.Println("Initializing git repository...")
	if err := run.CommandQuiet(dir, "git", "init"); err != nil {
		fmt.Printf("  warning: git init failed: %v\n", err)
	} else {
		_ = run.CommandQuiet(dir, "git", "add", "-A")
		if err := run.CommandQuiet(dir, "git", "commit", "-m", "Initialize "+opts.Name+" (generated by gor)"); err != nil {
			fmt.Println("  warning: initial commit failed (is git user.name/user.email configured?)")
		}
	}

	return printNextSteps(opts.Name)
}

func printNextSteps(name string) error {
	fmt.Printf(`
Done! Next steps:

  cd %s
  gor db setup    # start Postgres (Docker) and migrate
  gor dev         # http://localhost:5173

Generate your first resource:

  gor g resource post title:string body:text published:bool
`, name)
	return nil
}
